/**
 * AI 命令的 Node 运行时回落。
 *
 * 打包态后端本身就是被 Electron 以 ELECTRON_RUN_AS_NODE 启动的（process.execPath 即 GuaDa 可执行文件，
 * 见 electron/main.ts 生产分支），但 AI 的 run_command 走的是用户 shell：它继承的是 GUI 进程的 PATH，
 * 里面只有用户自己安装的 node。macOS 从 launchd 启动的 GUI 进程 PATH 通常只有
 * /usr/bin:/bin:/usr/sbin:/sbin，nvm/fnm 装的 node 根本不在其中，于是命令里的 node 直接 command not found。
 * 这里把内置 Node 以 shim 形式补进命令的 PATH。
 *
 * 两个刻意的设计：
 * - 追加到 PATH 末尾而不是前置：用户装了 node 就用用户的，没装才回落到内置 Node，不改变现有行为。
 * - ELECTRON_RUN_AS_NODE 只在 shim 进程内部设置，不写进命令的 env：一旦写进 env，命令里启动的任何
 *   Electron 可执行文件都会退化成 Node 模式。zcode 同样为此把该变量从运行环境里剔除。
 *
 * shim 在运行时按需写入用户数据目录，而不是随包分发：git 在 Windows 检出（core.filemode=false）保留不了
 * POSIX 可执行位，随包脚本在 macOS 上会因缺少 +x 而无法被 bash 命中；运行时写入可以自己 chmod。
 *
 * 边界：只提供 `node`。Electron 不自带 npm/npx，`npm install` 这类命令仍需要用户自装 Node；
 * 走内置 Node 时 process.versions.electron 有值，编译原生模块（node-gyp）可能因 ABI 目标不同而失败。
 */
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";

/** shim 类型：posix 供 bash/sh，win 供 PowerShell/cmd */
export type NodeShimKind = "posix" | "win";

/** 内置 Node 可执行文件路径的传递变量：本模块注入，shim 消费 */
const ELECTRON_BIN_ENV = "GUADA_ELECTRON_BIN";

const SHIM_FILE_NAME: Record<NodeShimKind, string> = {
  posix: "node",
  win: "node.cmd",
};

const POSIX_SHIM = `#!/bin/sh
# GuaDa 内置 Node 回落入口（由 backend-ts 的 node-shim.util.ts 生成）。
if [ -z "$${ELECTRON_BIN_ENV}" ]; then
  echo "guada node shim: ${ELECTRON_BIN_ENV} is not set" >&2
  exit 127
fi
ELECTRON_RUN_AS_NODE=1 exec "$${ELECTRON_BIN_ENV}" "$@"
`;

// cmd.exe 按 OEM 代码页读取 .cmd，非 ASCII 注释会变成乱码，所以 win shim 只用 ASCII。
const WIN_SHIM = `@echo off
rem GuaDa built-in Node fallback shim (generated by backend-ts node-shim.util.ts).
if "%${ELECTRON_BIN_ENV}%"=="" (
  echo guada node shim: ${ELECTRON_BIN_ENV} is not set 1>&2
  exit /b 127
)
set "ELECTRON_RUN_AS_NODE=1"
"%${ELECTRON_BIN_ENV}%" %*
`;

/**
 * 解析可用于执行 JS 的 Electron 可执行文件。
 *
 * 打包态：后端是被 Electron 以 ELECTRON_RUN_AS_NODE 启动的，process.versions.electron 有值、
 * execPath 就是 GuaDa 可执行文件本身（zcode 用同一个门控）。
 * 开发态：跑在纯 Node 上，execPath 是 node.exe，改从 electron 包取二进制路径；取不到就整体不启用
 * （开发机本来就装了 node，没有回落需求）。
 */
function resolveElectronBin(): string | null {
  // 显式覆盖（也用于单测固定运行时，避免依赖 electron 包是否可解析）。
  // 覆盖具权威性：指向不存在的路径时视为"无可用运行时"，不再回退到 electron 包——
  // 否则调用方无法通过覆盖关闭 shim（单测也无法确定性复现该分支）。
  const override = process.env[ELECTRON_BIN_ENV]?.trim();
  if (override) {
    return fs.existsSync(override) ? override : null;
  }

  if (process.versions.electron && process.execPath) {
    return process.execPath;
  }

  try {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const electronPath = require("electron");
    if (typeof electronPath === "string" && fs.existsSync(electronPath)) {
      return electronPath;
    }
  } catch {
    // 未安装 electron 包：不启用 shim
  }
  return null;
}

/** shim 落盘根目录：用户数据目录优先，兜底临时目录 */
function resolveShimRoot(): string {
  const override = process.env.GUADA_RUNTIME_BIN_DIR?.trim();
  if (override) return override;

  const dataRoot = process.env.USERDATA_DIR || process.env.SETTINGS_DIR;
  if (dataRoot) return path.join(dataRoot, "runtime-bin");

  return path.join(os.tmpdir(), "guada-runtime-bin");
}

/**
 * 确保 shim 落盘并返回其所在目录；不可用时返回 null（调用方保持原环境，不报错）。
 */
export function resolveNodeShimDir(kind: NodeShimKind): string | null {
  const dir = path.join(resolveShimRoot(), kind);
  const file = path.join(dir, SHIM_FILE_NAME[kind]);
  const content = kind === "posix" ? POSIX_SHIM : WIN_SHIM;

  try {
    fs.mkdirSync(dir, { recursive: true });
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
      fs.writeFileSync(file, content, { encoding: "utf8", mode: 0o755 });
    }
    // 已存在但缺可执行位时补齐（bash 会跳过不可执行的 PATH 候选，静默退回"没装 node"）。
    if (kind === "posix") fs.chmodSync(file, 0o755);
    return dir;
  } catch {
    return null;
  }
}

/**
 * 把内置 Node shim 追加到命令环境的 PATH 末尾，并注入 shim 所需的可执行文件路径。
 * 环境不可用（无 Electron 二进制 / shim 写不进去）时原样返回。
 */
export function applyNodeShim(
  env: NodeJS.ProcessEnv,
  kind: NodeShimKind,
): NodeJS.ProcessEnv {
  const electronBin = resolveElectronBin();
  if (!electronBin) return env;

  const shimDir = resolveNodeShimDir(kind);
  if (!shimDir) return env;

  // Windows 上 PATH 的实际键名是 Path，且 Path 与 PATH 同时存在时子进程只会保留其中一个，
  // 于是追加可能被另一个短键覆盖。这里统一收敛成单个 PATH 键。
  let current: string | undefined;
  for (const key of Object.keys(env)) {
    if (key.toUpperCase() === "PATH") {
      if (current === undefined) current = env[key];
      delete env[key];
    }
  }

  const entries = (current ?? "").split(path.delimiter).filter(Boolean);
  if (!entries.includes(shimDir)) entries.push(shimDir);
  if (entries.length > 0) env.PATH = entries.join(path.delimiter);

  env[ELECTRON_BIN_ENV] = electronBin;
  return env;
}
