/**
 * 工作目录比较键（单一真相）。
 *
 * 会话的 `workspace_path` 是**逐字存储**的：历史数据里同一个目录出现过
 * `D:/AI/work/public` 与 `D:\AI\work\public` 两种写法（实测 31 条 + 1 条）。
 * 按目录分组必须先把它们归一到同一个键，否则同一目录会裂成两个分组。
 *
 * 归一化只做三件事，刻意保持保守：
 * 1. `path.resolve` —— 消 `.`/`..`、补全分隔符；
 * 2. 分隔符统一为 `/`、去末尾分隔符（保留根：`/` 与 `C:/`）；
 * 3. **仅 win32** 转小写 —— Windows 文件系统大小写不敏感；POSIX 保留原样，
 *    避免把两个真实存在的不同目录误并。
 *
 * 不做 realpath / 符号链接消解：代码库既有的路径处理均未使用 realpath，
 * 且历史目录可能已不存在。符号链接别名会成为独立分组，属已知限制。
 */
import * as path from "path";

/** 自动生成的工作目录名：`WORK-YYYY-MM-DD-XXXX` / `BOT-YYYY-MM-DD-XXXX` */
export const AUTO_WORKSPACE_DIR_PATTERN =
  /^(?:work|bot)-\d{4}-\d{2}-\d{2}-[a-z0-9]{4}$/i;

/** 取路径末段（同时接受 `\` 与 `/`，不依赖调用方平台） */
export function workspaceBasename(input: string): string {
  const unified = input.replace(/[\\/]+/g, "/").replace(/\/+$/, "");
  const leaf = unified.split("/").filter(Boolean).pop();
  return leaf ?? "";
}

/** 归一化为比较键（见文件头注释） */
export function normalizeWorkspaceKey(input: string): string {
  const resolved = path.resolve(input);
  let unified = resolved.replace(/[\\/]+/g, "/");
  // 去末尾分隔符，但保留文件系统根（POSIX `/`、Windows `C:/`）
  while (unified.length > 1 && unified.endsWith("/")) {
    if (/^[A-Za-z]:\/$/.test(unified)) break;
    unified = unified.slice(0, -1);
  }
  return process.platform === "win32" ? unified.toLowerCase() : unified;
}

/** 是否后端自动生成的临时工作目录（`WORK-*` / `BOT-*`） */
export function isAutoGeneratedWorkspacePath(input: string): boolean {
  return AUTO_WORKSPACE_DIR_PATTERN.test(workspaceBasename(input));
}

/**
 * 是否为「公共目录」。
 *
 * 只按目录名判定，不限定父目录：应用自己的公共目录始终叫 `public`，而
 * `workspaceBaseDir` 会随配置/版本变化（实测同一台机器上同时存在
 * `<旧baseDir>/public`、`<新baseDir>/public`、`backend-ts/workspace/public`
 * 三处历史遗留）。只认「当前 baseDir 的直接子目录」会让这些目录各自变成
 * 独立分组，与用户「公共目录只有一个」的认知冲突。
 *
 * 代价：用户若有一个真实项目恰好也叫 `public`，会被并入「通用」。
 */
export function isPublicWorkspacePath(input: string): boolean {
  return workspaceBasename(input).toLowerCase() === "public";
}

/**
 * 是否值得物化为「目录分组」。
 *
 * 刻意**不**用「父目录 === baseDir」作为兜底：baseDir 下可能放着用户自选的
 * 真实项目（如 `D:\AI\work\kimi_proxy`），它们必须独立成组。只有公共目录
 * 和自动生成目录落进「通用」。
 */
export function qualifiesForProjectGroup(
  input: string | null | undefined,
  baseDir: string,
): boolean {
  if (!input) return false;
  if (isAutoGeneratedWorkspacePath(input)) return false;
  if (isPublicWorkspacePath(input)) return false;
  return true;
}
