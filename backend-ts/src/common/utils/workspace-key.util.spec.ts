import * as path from "path";
import {
  normalizeWorkspaceKey,
  workspaceBasename,
  isAutoGeneratedWorkspacePath,
  isPublicWorkspacePath,
  qualifiesForProjectGroup,
} from "./workspace-key.util";

/**
 * 工作目录比较键与「目录分组」资格判定。
 *
 * 真实数据依据：用户库里同一目录同时存在 `D:/AI/work/public`（31 条正斜杠）
 * 与 `D:\AI\work\public`（1 条反斜杠），不归一化会裂成两个分组。
 */
const isWin = process.platform === "win32";
const baseDir = isWin ? "D:\\AI\\work" : "/base";

describe("normalizeWorkspaceKey", () => {
  it("消解 . / .. 与末尾分隔符", () => {
    const expected = isWin ? "c:/a/c" : "/a/c";
    const input = isWin ? "C:\\a\\b\\..\\c\\" : "/a/b/../c/";
    expect(normalizeWorkspaceKey(input)).toBe(expected);
  });

  it("win32：同一目录的 / 与 \\ 两种写法归一为同键（真实库用例）", () => {
    if (!isWin) return;
    expect(normalizeWorkspaceKey("D:/AI/work/public")).toBe(
      normalizeWorkspaceKey("D:\\AI\\work\\public"),
    );
    expect(normalizeWorkspaceKey("D:/AI/work/public/")).toBe(
      "d:/ai/work/public",
    );
  });

  it("win32：盘符根不被削成 `c:`", () => {
    if (!isWin) return;
    expect(normalizeWorkspaceKey("C:\\")).toBe("c:/");
  });

  it("POSIX：区分大小写，不误并两个不同目录", () => {
    if (isWin) return;
    expect(normalizeWorkspaceKey("/A/B")).toBe("/A/B");
    expect(normalizeWorkspaceKey("/A/B")).not.toBe(
      normalizeWorkspaceKey("/a/b"),
    );
  });
});

describe("workspaceBasename", () => {
  it("同时接受反斜杠与正斜杠，并容忍末尾分隔符", () => {
    expect(workspaceBasename("D:\\AI\\work\\kimi_proxy")).toBe("kimi_proxy");
    expect(workspaceBasename("D:/AI/work/kimi_proxy/")).toBe("kimi_proxy");
  });
});

describe("isAutoGeneratedWorkspacePath", () => {
  it("识别 WORK-* / BOT-* 自动目录（大小写不敏感）", () => {
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\work\\WORK-2026-07-28-XvZL")).toBe(true);
    expect(isAutoGeneratedWorkspacePath("D:/AI/work/work-2026-07-28-xvzl")).toBe(true);
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\work\\BOT-2026-06-13-RgW2")).toBe(true);
  });

  it("真实项目目录不误判", () => {
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\work\\kimi_proxy")).toBe(false);
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\ai_chat")).toBe(false);
    // 日期格式不完整 / 随机段长度不对，都不算自动目录
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\work\\WORK-2026-07-28-XvZL-extra")).toBe(false);
    expect(isAutoGeneratedWorkspacePath("D:\\AI\\work\\WORK-2026-7-28-XvZL")).toBe(false);
  });
});

describe("qualifiesForProjectGroup", () => {
  it("空路径不合格", () => {
    expect(qualifiesForProjectGroup(null, baseDir)).toBe(false);
    expect(qualifiesForProjectGroup(undefined, baseDir)).toBe(false);
    expect(qualifiesForProjectGroup("", baseDir)).toBe(false);
  });

  it("自动生成目录不合格（归入通用）", () => {
    expect(qualifiesForProjectGroup(path.join(baseDir, "WORK-2026-07-28-XvZL"), baseDir)).toBe(false);
    expect(qualifiesForProjectGroup(path.join(baseDir, "BOT-2026-06-13-RgW2"), baseDir)).toBe(false);
  });

  it("任何名为 public 的目录不合格（baseDir 会变，历史 public 目录都应归一）", () => {
    expect(qualifiesForProjectGroup(path.join(baseDir, "public"), baseDir)).toBe(false);
    expect(qualifiesForProjectGroup(path.join(baseDir, "PUBLIC"), baseDir)).toBe(false);
    const otherPublic = isWin ? "D:\\projects\\public" : "/projects/public";
    expect(qualifiesForProjectGroup(otherPublic, baseDir)).toBe(false);
  });

  it("baseDir 下的真实项目必须独立成组（真实库用例 kimi_proxy）", () => {
    expect(qualifiesForProjectGroup(path.join(baseDir, "kimi_proxy"), baseDir)).toBe(true);
  });

  it("普通自定义目录合格", () => {
    expect(qualifiesForProjectGroup(isWin ? "D:\\AI\\ai_chat" : "/ai/ai_chat", baseDir)).toBe(true);
  });
});

describe("isPublicWorkspacePath", () => {
  it("按目录名判定（不论父目录），排除大小写差异", () => {
    expect(isPublicWorkspacePath(path.join(baseDir, "public"))).toBe(true);
    expect(isPublicWorkspacePath(path.join(baseDir, "sub", "public"))).toBe(true);
    expect(isPublicWorkspacePath(isWin ? "D:\\other\\PUBLIC" : "/other/PUBLIC")).toBe(true);
    expect(isPublicWorkspacePath(path.join(baseDir, "public2"))).toBe(false);
  });
});
